#!/usr/bin/env bash
# Deploys the portal WAR to Tomcat 11 as /certportal-<env> through the Manager text API.
#
#   scripts/deploy-tomcat.sh <war> <staging|production>
#
# Environment-specific settings are passed as Tomcat context parameters, which Spring Boot reads as
# configuration (ServletContext init parameters), so one WAR serves every environment.
# Required env: TOMCAT_URL, TOMCAT_USER, TOMCAT_PASSWORD, OFFICER_PASSWORD
# Optional env: TOMCAT_CONTAINER (default ccrp-tomcat), APP_VERSION
set -euo pipefail

WAR=${1:?usage: deploy-tomcat.sh <war> <staging|production>}
ENV_NAME=${2:?usage: deploy-tomcat.sh <war> <staging|production>}
case "$ENV_NAME" in staging|production) ;; *) echo "TARGET_ENV must be staging or production, got '$ENV_NAME'" >&2; exit 2 ;; esac
: "${TOMCAT_URL:?}" "${TOMCAT_USER:?}" "${TOMCAT_PASSWORD:?}" "${OFFICER_PASSWORD:?}"

CONTAINER=${TOMCAT_CONTAINER:-ccrp-tomcat}
CTX="certportal-${ENV_NAME}"
STAGE=/usr/local/tomcat/deployments
VERSION=${APP_VERSION:-unknown}

manager() { curl -sS --fail-with-body -u "$TOMCAT_USER:$TOMCAT_PASSWORD" "$TOMCAT_URL/manager/text/$1"; }

tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
cat > "$tmp/$CTX.xml" <<XML
<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/deploy-tomcat.sh · environment=$ENV_NAME · version=$VERSION -->
<Context>
  <Parameter name="app.environment" value="$ENV_NAME" override="false"/>
  <Parameter name="app.data-dir" value="/usr/local/tomcat/data/$ENV_NAME" override="false"/>
  <Parameter name="app.officer.password" value="$OFFICER_PASSWORD" override="false"/>
</Context>
XML

echo "==> Deploying $(basename "$WAR") ($VERSION) to $TOMCAT_URL/$CTX"
docker exec "$CONTAINER" mkdir -p "$STAGE" "/usr/local/tomcat/data/$ENV_NAME"
docker cp "$WAR" "$CONTAINER:$STAGE/$CTX.war"
docker cp "$tmp/$CTX.xml" "$CONTAINER:$STAGE/$CTX.xml"

if manager list | grep -q "^/$CTX:"; then
  echo "==> Undeploying the running version of /$CTX"
  manager "undeploy?path=/$CTX"
fi

echo "==> Manager deploy (context descriptor + WAR)"
manager "deploy?path=/$CTX&config=file:$STAGE/$CTX.xml&war=file:$STAGE/$CTX.war&tag=$VERSION" | tee "$tmp/deploy.out"
grep -q '^OK' "$tmp/deploy.out"

echo "==> Waiting for /$CTX to report healthy"
for i in $(seq 1 90); do
  if curl -fsS "$TOMCAT_URL/$CTX/actuator/health" 2>/dev/null | grep -q '"UP"'; then
    echo "Healthy after ~$((i * 2))s"
    manager list | grep "^/$CTX:"
    exit 0
  fi
  sleep 2
done
echo "/$CTX did not become healthy in time" >&2
docker logs --tail 120 "$CONTAINER" >&2
exit 1
