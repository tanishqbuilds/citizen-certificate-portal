-- CCR-3 / CCR-12: certificate requests and their status history.
CREATE TABLE certificate_request (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tracking_id            VARCHAR(20)  NOT NULL,
    certificate_type       VARCHAR(20)  NOT NULL,
    status                 VARCHAR(20)  NOT NULL,
    applicant_name         VARCHAR(100) NOT NULL,
    date_of_birth          DATE         NOT NULL,
    email                  VARCHAR(254) NOT NULL,
    phone                  VARCHAR(10)  NOT NULL,
    national_id_masked     VARCHAR(14)  NOT NULL,
    national_id_hash       VARCHAR(64)  NOT NULL,
    address                VARCHAR(300) NOT NULL,
    district               VARCHAR(60)  NOT NULL,
    pin_code               VARCHAR(6)   NOT NULL,
    purpose                VARCHAR(300) NOT NULL,
    annual_income          BIGINT,
    spouse_name            VARCHAR(100),
    document_name          VARCHAR(255) NOT NULL,
    document_content_type  VARCHAR(50)  NOT NULL,
    document_size          BIGINT       NOT NULL,
    document_sha256        VARCHAR(64)  NOT NULL,
    document_path          VARCHAR(500) NOT NULL,
    certificate_number     VARCHAR(40),
    certificate_hash       VARCHAR(64),
    decision_remarks       VARCHAR(500),
    reviewed_by            VARCHAR(50),
    submitted_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at             TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    decided_at             TIMESTAMP(6) WITH TIME ZONE,
    version                INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT uk_request_tracking_id UNIQUE (tracking_id),
    CONSTRAINT uk_request_certificate_number UNIQUE (certificate_number),
    CONSTRAINT ck_request_status CHECK (status IN ('SUBMITTED', 'UNDER_REVIEW', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_request_type CHECK (certificate_type IN ('BIRTH', 'INCOME', 'DOMICILE', 'MARRIAGE'))
);

CREATE INDEX ix_request_status_submitted ON certificate_request (status, submitted_at);

CREATE TABLE status_event (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id   BIGINT       NOT NULL,
    from_status  VARCHAR(20),
    to_status    VARCHAR(20)  NOT NULL,
    actor        VARCHAR(50)  NOT NULL,
    remarks      VARCHAR(500),
    occurred_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_status_event_request FOREIGN KEY (request_id) REFERENCES certificate_request (id) ON DELETE CASCADE
);

CREATE INDEX ix_status_event_request ON status_event (request_id, occurred_at);
